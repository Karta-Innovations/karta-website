/** Width divided by cap height for each line of the wordmark. */
export const KARTA_RATIO = 71.3 / 14.2;
export const INNOVATIONS_RATIO = 100.6 / 10.4;

interface WordmarkProps {
  /** Cap height in pixels. */
  size?: number;
  /** Draw the `INNOVATIONS` descriptor line instead of `KARTA`. */
  line?: "karta" | "innovations";
  /**
   * Thickens the hairline strokes slightly so the wordmark holds at small
   * sizes. The artwork is drawn light; below ~18 px it needs the help.
   */
  optical?: boolean;
  className?: string;
  title?: string;
}

export function Wordmark({ size = 14, line = "karta", optical, className, title }: WordmarkProps) {
  const karta = line === "karta";
  const ratio = karta ? KARTA_RATIO : INNOVATIONS_RATIO;
  const boost = optical ?? size < 18;

  return (
    <svg
      viewBox={karta ? "79.3 114.1 71.3 14.2" : "79 134.6 100.6 10.4"}
      width={Math.round(size * ratio * 100) / 100}
      height={size}
      className={cn("wordmark", className)}
      role={title ? "img" : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      focusable="false"
      overflow="visible"
    >
      <path
        d={karta ? KARTA : INNOVATIONS}
        fill="currentColor"
        fillRule="evenodd"
        stroke={boost ? "currentColor" : undefined}
        strokeWidth={boost ? (karta ? 0.42 : 0.3) : undefined}
        strokeLinejoin="round"
      />
    </svg>
  );
}
